"""No compiled binaries in the tree, and the Gradle wrapper is generated instead of shipped.

Review item 1: the repo tracked `android/gradle/wrapper/gradle-wrapper.jar` and
`wear/gradle/wrapper/gradle-wrapper.jar`. A JAR is a compiled binary nobody can review, and a catalog
that lists plugins cannot carry unreviewable blobs — so the wrappers are generated by CI (and by anyone
building locally) from the tracked properties file, which pins the distribution checksum.

These tests fail on the tree as reviewed and pass once the jars are gone and the workflows generate
them: they read the filesystem and the workflow YAML, not a claim in the docs.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

PROJECTS = ("android", "wear")


def test_no_tracked_gradle_wrapper_jar() -> None:
    found = [str(p.relative_to(ROOT)) for project in PROJECTS
             for p in (ROOT / project / "gradle" / "wrapper").glob("*.jar")]
    assert not found, (
        "prebuilt binaries in the tree: " + ", ".join(found)
        + " — the wrapper is generated by CI and by `gradle wrapper`, never committed"
    )


def test_no_binary_blobs_anywhere_in_the_android_projects() -> None:
    """A jar anywhere under the app projects is the same finding, not just in the wrapper folder."""
    blobs = [str(p.relative_to(ROOT)) for project in PROJECTS
             for p in (ROOT / project).rglob("*.jar")
             if ".gradle" not in p.parts and "build" not in p.parts]
    assert not blobs, "compiled binaries in the tree: " + ", ".join(blobs)


def test_ci_generates_the_wrapper_before_building() -> None:
    for workflow in (".github/workflows/android.yml", ".github/workflows/wear.yml"):
        text = (ROOT / workflow).read_text(encoding="utf-8")
        assert "gradle wrapper --gradle-version" in text, (
            f"{workflow} runs ./gradlew without generating the wrapper first"
        )


def test_the_wrapper_properties_pin_the_distribution_checksum() -> None:
    """If the JAR is generated, the download it produces must be the one we meant."""
    for project in PROJECTS:
        props = (ROOT / project / "gradle" / "wrapper" / "gradle-wrapper.properties").read_text(encoding="utf-8")
        assert "distributionUrl=" in props
        checksum = next((line.split("=", 1)[1].strip() for line in props.splitlines()
                         if line.startswith("distributionSha256Sum=")), "")
        assert len(checksum) == 64 and all(c in "0123456789abcdef" for c in checksum), (
            f"{project}/gradle-wrapper.properties needs a distributionSha256Sum"
        )
